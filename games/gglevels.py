import json
L = []
def lvl(name, rows):
    rows = [r.ljust(28)[:28] if len(r) <= 28 else r for r in rows]
    for i, r in enumerate(rows):
        assert len(r) == 28, (name, i, len(r), r)
    assert len(rows) == 16, (name, len(rows))
    L.append({'name': name, 'map': rows})

